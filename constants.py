# disc function for photometric correction
import numpy as np


def disc_function(inc, emi, pha):
    '''
    :param inc: float
           incidence angle (deg)
    :param emi: float
           emission angle (deg)
    :param pha: float
           phase angle (deg)
    :return: disc_fun

    This function calculates the Akimov disk function for the Kaasaleinen-Shkuratov photometric model as implemented for
    Enceladus by Robidel et al. 2020.
    '''

    gamma = np.arctan((np.cos(np.deg2rad(inc)) - np.cos(np.deg2rad(emi)) * np.cos(np.deg2rad(pha))) /
                      (np.cos(np.deg2rad(emi)) * np.sin(np.deg2rad(pha))))

    beta = np.arccos(np.cos(np.deg2rad(emi)) / np.cos(gamma))

    disc_fun = np.cos(np.deg2rad(pha) / 2) * np.cos(
        (np.pi / (np.pi - np.deg2rad(pha))) * (gamma - np.deg2rad(pha) / 2)) * \
               np.power(np.cos(beta), np.deg2rad(pha) / (np.pi - np.deg2rad(pha))) / np.cos(gamma)

    return disc_fun


# bounding box and connecting lines for zoom panel in figure
from mpl_toolkits.axes_grid1.inset_locator import mark_inset, TransformedBbox, BboxPatch, BboxConnector


def mark_inset_2(parent_axes, inset_axes, loc1a=1, loc1b=1, loc2a=2, loc2b=2, **kwargs):
    rect = TransformedBbox(inset_axes.viewLim, parent_axes.transData)

    pp = BboxPatch(rect, fill=False, **kwargs)
    parent_axes.add_patch(pp)

    p1 = BboxConnector(inset_axes.bbox, rect, loc1=loc1a, loc2=loc1b, **kwargs)
    inset_axes.add_patch(p1)
    p1.set_clip_on(False)
    p2 = BboxConnector(inset_axes.bbox, rect, loc1=loc2a, loc2=loc2b, **kwargs)
    inset_axes.add_patch(p2)
    p2.set_clip_on(False)

    return pp, p1, p2
