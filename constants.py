def disc_function(inc, emi, pha):
    '''
    :param inc: float
           incidence angle (deg)
    :param emi: float
           emission angle (deg)
    :param pha: float
           phase angle (deg)
    :return: disc_fun

    This function calculates the Akimov disk function for the Kaasaleinen-Shkuratov photometric model as implemented for
    Enceladus by Robidel et al. 2020.
    '''

    gamma = np.arctan((np.cos(np.deg2rad(inc)) - np.cos(np.deg2rad(emi)) * np.cos(np.deg2rad(pha))) /
                      (np.cos(np.deg2rad(emi)) * np.sin(np.deg2rad(pha))))

    beta = np.arccos(np.cos(np.deg2rad(emi)) / np.cos(gamma))

    disc_fun = np.cos(np.deg2rad(pha) / 2) * np.cos(
        (np.pi / (np.pi - np.deg2rad(pha))) * (gamma - np.deg2rad(pha) / 2)) * \
               np.power(np.cos(beta), np.deg2rad(pha) / (np.pi - np.deg2rad(pha))) / np.cos(gamma)

    return disc_fun

